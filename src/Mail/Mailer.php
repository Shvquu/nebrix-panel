<?php

declare(strict_types=1);

namespace Nebrix\Mail;

use Nebrix\Core\Config;
use Nebrix\Queue\JobQueue;
use Nebrix\Security\Encrypter;
use Nebrix\Settings\SettingsRepository;
use PHPMailer\PHPMailer\Exception as PHPMailerException;
use PHPMailer\PHPMailer\PHPMailer;
use PHPMailer\PHPMailer\SMTP;
use Psr\Log\LoggerInterface;
use RuntimeException;

/**
 * Sends e-mails through SMTP (PHPMailer) using the settings from the admin
 * panel. Messages are queued as background jobs; the queued payload is
 * encrypted because it can contain single-use links (verification, reset).
 */
class Mailer
{
    public const JOB_TYPE = 'mail.send';

    public function __construct(
        private readonly SettingsRepository $settings,
        private readonly JobQueue $queue,
        private readonly MailTemplates $templates,
        private readonly Encrypter $encrypter,
        private readonly LoggerInterface $logger,
        private readonly Config $config,
        private readonly \Nebrix\Database\Connection $db,
        private readonly ?\Nebrix\Notification\NotificationRouter $notifications = null,
    ) {
    }

    /**
     * Queues a templated e-mail in the recipient's language: $locale, else
     * the language of the account with this address, else the default
     * language of the installation.
     *
     * @param array<string, scalar|null> $variables
     * @param list<array{filename: string, content: string, mime: string}> $attachments stored encrypted with the queued message
     * @param int|null $invoiceDocuments ID of an invoice whose documents (PDF, XRechnung) are attached when the
     *                                   mail is sent – they are generated by the worker, after the caller's transaction
     * @param array{reply_to?: string, list_unsubscribe?: string} $headers Reply-To instead of the support address;
     *                                   List-Unsubscribe URL (also sent as RFC 8058 one-click)
     */
    public function queue(string $toEmail, ?string $toName, string $template, array $variables = [], ?string $locale = null, array $attachments = [], ?int $invoiceDocuments = null, array $headers = []): void
    {
        // Customers can switch off some notifications (Account → Notifications); mandatory e-mails are always sent.
        if ($this->notifications !== null && !$this->notifications->route($toEmail, $template, $variables)) {
            $this->logger->info('E-mail not sent (switched off by the recipient)', ['template' => $template]);

            return;
        }

        $message = $this->templates->render($template, $variables, $locale ?? $this->localeFor($toEmail)) + [
            'to' => $toEmail,
            'to_name' => $toName ?? '',
            'template' => $template,
            'attachments' => array_map(static fn (array $a): array => [
                'filename' => (string) preg_replace('/[^A-Za-z0-9._-]/', '_', $a['filename']),
                'content' => base64_encode($a['content']),
                'mime' => in_array($a['mime'], ['application/pdf', 'application/xml'], true) ? $a['mime'] : 'application/octet-stream',
            ], $attachments),
            'invoice_documents' => $invoiceDocuments,
            'headers' => self::headers($headers),
        ];

        $this->queue->dispatch(self::JOB_TYPE, [
            'template' => $template,
            'message' => $this->encrypter->encryptArray($message, 'mail-job'),
        ], null, 5);
    }

    /**
     * @param array<string, mixed> $payload job payload created by queue()
     * @param (callable(int): list<array{filename: string, content: string, mime: string}>)|null $invoiceDocuments
     */
    public function sendQueued(array $payload, ?callable $invoiceDocuments = null): void
    {
        /** @var array{to: string, to_name: string, subject: string, html: string, text: string, template: string, attachments?: list<array{filename: string, content: string, mime: string}>, invoice_documents?: int|null, headers?: array{reply_to?: string, list_unsubscribe?: string}} $message */
        $message = $this->encrypter->decryptArray((string) ($payload['message'] ?? ''), 'mail-job');
        if (($message['invoice_documents'] ?? null) !== null && $invoiceDocuments !== null) {
            foreach ($invoiceDocuments((int) $message['invoice_documents']) as $document) {
                $message['attachments'][] = ['filename' => (string) preg_replace('/[^A-Za-z0-9._-]/', '_', $document['filename']), 'content' => base64_encode($document['content']), 'mime' => in_array($document['mime'], ['application/pdf', 'application/xml'], true) ? $document['mime'] : 'application/octet-stream'];
            }
        }
        $this->deliver($message);
    }

    /**
     * Sends immediately (used for the SMTP test in the admin panel).
     *
     * @param array<string, scalar|null> $variables
     *
     * @throws RuntimeException with a safe error description
     */
    public function sendNow(string $toEmail, ?string $toName, string $template, array $variables = []): void
    {
        $this->deliver($this->templates->render($template, $variables, $this->localeFor($toEmail)) + [
            'to' => $toEmail,
            'to_name' => $toName ?? '',
            'template' => $template,
        ], true);
    }

    /**
     * Only well-formed values are kept (no line breaks, valid address / http(s) URL).
     *
     * @param array{reply_to?: string, list_unsubscribe?: string} $headers
     * @return array{reply_to?: string, list_unsubscribe?: string}
     */
    private static function headers(array $headers): array
    {
        $clean = [];
        $replyTo = trim((string) ($headers['reply_to'] ?? ''));
        if ($replyTo !== '' && filter_var($replyTo, FILTER_VALIDATE_EMAIL) !== false && preg_match('/[\r\n<>]/', $replyTo) !== 1) {
            $clean['reply_to'] = $replyTo;
        }
        $unsubscribe = trim((string) ($headers['list_unsubscribe'] ?? ''));
        if ($unsubscribe !== '' && preg_match('#^https?://[^\s<>"]+$#', $unsubscribe) === 1) {
            $clean['list_unsubscribe'] = $unsubscribe;
        }

        return $clean;
    }

    /**
     * @param array{to: string, to_name: string, subject: string, html: string, text: string, template: string, attachments?: list<array{filename: string, content: string, mime: string}>, headers?: array{reply_to?: string, list_unsubscribe?: string}} $message
     */
    private function deliver(array $message, bool $diagnose = false): void
    {
        if (filter_var($message['to'], FILTER_VALIDATE_EMAIL) === false) {
            throw new RuntimeException('Invalid recipient address.');
        }

        if (!$this->settings->bool('mail.enabled')) {
            // Development / not configured: record the message without its body in production.
            $context = ['to' => $message['to'], 'subject' => $message['subject'], 'template' => $message['template']];
            if ($this->config->string('app.env') === 'local') {
                $context['body'] = $message['text'];
            }
            $this->logger->info('E-mail not sent (SMTP disabled in settings)', $context);

            return;
        }

        $mail = $this->createMailer();
        $lines = [];
        if ($diagnose) {
            $this->captureServerDialogue($mail, $lines);
        }
        try {
            $mail->addAddress($message['to'], $message['to_name']);
            $mail->Subject = $message['subject'];
            $mail->Body = $message['html'];
            $mail->AltBody = $message['text'];
            $headers = self::headers($message['headers'] ?? []);
            if (isset($headers['reply_to'])) {
                $mail->clearReplyTos();
                $mail->addReplyTo($headers['reply_to']);
            }
            if (isset($headers['list_unsubscribe'])) {
                $mail->addCustomHeader('List-Unsubscribe', '<' . $headers['list_unsubscribe'] . '>');
                $mail->addCustomHeader('List-Unsubscribe-Post', 'List-Unsubscribe=One-Click');
            }
            foreach ($message['attachments'] ?? [] as $attachment) {
                $mail->addStringAttachment((string) base64_decode($attachment['content'], true), $attachment['filename'], PHPMailer::ENCODING_BASE64, $attachment['mime']);
            }
            $mail->send();
        } catch (PHPMailerException $exception) {
            throw new RuntimeException('SMTP delivery failed: ' . $this->diagnosis($mail->ErrorInfo ?: $exception->getMessage(), $lines), 0, $exception);
        }

        $this->logger->info('E-mail sent', ['to' => $message['to'], 'template' => $message['template']]);
    }

    /**
     * Opens and closes an SMTP connection to validate host, encryption and
     * credentials without sending a message.
     *
     * @throws RuntimeException
     */
    public function testConnection(): void
    {
        $mail = $this->createMailer();
        $lines = [];
        $this->captureServerDialogue($mail, $lines);
        try {
            if (!$mail->smtpConnect()) {
                throw new RuntimeException('Could not connect or authenticate: ' . $this->diagnosis($mail->ErrorInfo, $lines));
            }
            $mail->smtpClose();
        } catch (PHPMailerException $exception) {
            throw new RuntimeException('SMTP connection failed: ' . $this->diagnosis($exception->getMessage(), $lines), 0, $exception);
        }
    }

    private function createMailer(): PHPMailer
    {
        $host = $this->settings->string('mail.host');
        if ($host === '') {
            throw new RuntimeException('No SMTP host is configured.');
        }

        $mail = new PHPMailer(true);
        $mail->isSMTP();
        $mail->Host = $host;
        $mail->Port = $this->settings->int('mail.port') ?: 587;
        $mail->CharSet = PHPMailer::CHARSET_UTF8;
        $mail->Timeout = 15;
        $mail->SMTPDebug = SMTP::DEBUG_OFF;
        $mail->isHTML(true);

        // A mail server on this machine may use a self-signed certificate
        // (e.g. Plesk without a domain); never relaxed for remote servers.
        if (!$this->settings->bool('mail.verify_tls') && self::isLoopback($host)) {
            $mail->SMTPOptions = ['ssl' => ['verify_peer' => false, 'verify_peer_name' => false, 'allow_self_signed' => true]];
        }

        $encryption = $this->settings->string('mail.encryption');
        if ($encryption === 'ssl') {
            $mail->SMTPSecure = PHPMailer::ENCRYPTION_SMTPS;
        } elseif ($encryption === 'tls') {
            $mail->SMTPSecure = PHPMailer::ENCRYPTION_STARTTLS;
        } else {
            $mail->SMTPSecure = '';
            $mail->SMTPAutoTLS = false;
        }

        $username = $this->settings->string('mail.username');
        if ($username !== '') {
            $mail->SMTPAuth = true;
            $mail->Username = $username;
            $mail->Password = (string) $this->settings->get('mail.password');
        }

        $from = $this->settings->string('mail.from_address');
        if ($from === '') {
            throw new RuntimeException('No sender address is configured.');
        }
        $mail->setFrom($from, $this->settings->string('mail.from_name'));
        $replyTo = $this->settings->string('general.support_email');
        if ($replyTo !== '') {
            $mail->addReplyTo($replyTo);
        }

        return $mail;
    }

    public static function isLoopback(string $host): bool
    {
        $host = strtolower(trim($host, '[] '));
        if ($host === 'localhost') {
            return true;
        }
        // Only literal loopback addresses – a name such as "127.mail.example.net" is not local.
        if (filter_var($host, FILTER_VALIDATE_IP) === false) {
            return false;
        }

        return \Nebrix\Http\IpRange::contains('127.0.0.0/8', $host) || \Nebrix\Http\IpRange::contains('::1/128', $host);
    }

    /**
     * Collects what the SMTP server answered (never what the client sent:
     * those lines can contain the encoded credentials) for error messages
     * of the admin tests.
     *
     * @param list<string> $lines
     */
    private function captureServerDialogue(PHPMailer $mail, array &$lines): void
    {
        $mail->SMTPDebug = SMTP::DEBUG_CONNECTION;
        $mail->Debugoutput = static function (string $line) use (&$lines): void {
            $line = trim(preg_replace('/\s+/', ' ', $line) ?? '');
            if (str_starts_with($line, 'CLIENT -> SERVER')) {
                return;
            }
            if (str_starts_with($line, 'SERVER -> CLIENT:') || preg_match('/Connection failed|SMTP ERROR|certificate|SSL|TLS|Error #/i', $line) === 1) {
                $lines[] = mb_substr(str_replace('SERVER -> CLIENT: ', '', $line), 0, 200);
            }
        };
    }

    /**
     * @param list<string> $lines
     */
    private function diagnosis(string $error, array $lines): string
    {
        // The last server answers usually name the cause (e.g. "535 authentication failed").
        $relevant = array_values(array_filter($lines, static fn (string $line): bool => preg_match('/^[45]\d\d|failed|error|certificate|ssl|tls/i', $line) === 1));
        $detail = implode(' | ', array_slice($relevant !== [] ? $relevant : $lines, -3));

        return $this->sanitizeError($error . ($detail !== '' ? ' – ' . $detail : ''));
    }

    private function sanitizeError(string $error): string
    {
        // Never echo credentials back (some servers include the username in errors).
        $password = (string) $this->settings->get('mail.password');
        if ($password !== '') {
            $error = str_replace($password, '[redacted]', $error);
        }

        return mb_substr(trim($error), 0, 300);
    }

    /** Language for e-mails to this address (account language, else the default language). */
    public function localeFor(string $email, ?string $fallback = null): string
    {
        $language = $this->db->fetchValue('SELECT `language` FROM `nx_users` WHERE `email` = ?', [mb_strtolower($email)]);
        if (is_string($language) && $language !== '') {
            return $language;
        }
        if ($fallback !== null && in_array($fallback, $this->templates->locales(), true)) {
            return $fallback;
        }

        return $this->settings->string('general.default_language') ?: MailTemplates::DEFAULT_LOCALE;
    }
}
